package com.barrybecker4.puzzle.benchmark

import java.util.Locale

/**
  * Renders the recorded benchmark runs as a markdown report with one table per puzzle and one column per
  * bb4-optimization version. Rows are every (variant, algorithm) pair seen in any run, so an algorithm that only
  * exists in a newer version shows "n/a" in the older version's column.
  */
object ReportGenerator {

  val NOT_AVAILABLE = "n/a"

  def render(runs: List[RunRecord]): String = {
    val sb = new StringBuilder
    sb.append("# Optimizer-backed solver benchmarks\n\n")
    sb.append("How long each bb4-optimization strategy takes to solve each puzzle variant, per bb4-optimization version.\n")
    sb.append("This file is generated by `./gradlew benchmarkReport` from `benchmarks.json`; do not edit it by hand.\n\n")
    if (runs.isEmpty) {
      sb.append("No results have been recorded yet. Run `./gradlew benchmark` to record a baseline.\n")
    } else {
      appendRuns(sb, runs)
      appendHowToRead(sb)
      puzzleNames(runs).foreach(puzzle => appendPuzzle(sb, puzzle, runs))
    }
    sb.toString
  }

  private def appendRuns(sb: StringBuilder, runs: List[RunRecord]): Unit = {
    sb.append("## Runs\n\n")
    sb.append("| Library | Date | Machine | Time limit | Repetitions |\n")
    sb.append("|---------|------|---------|------------|-------------|\n")
    runs.foreach { r =>
      val m = r.machine
      sb.append(s"| ${columnTitle(r)} | ${r.timestamp.take(10)} | ${m.cpus} CPUs, ${m.os} ${m.arch}, Java ${m.java}, " +
        s"${m.maxHeapMb} MB heap | ${r.timeoutSeconds}s | ${r.repetitions} |\n")
    }
    sb.append("\n")
    if (runs.map(_.machine).distinct.size > 1) {
      sb.append("**Note:** the runs above were made on different machines, so their timings are not directly comparable.\n\n")
    }
  }

  private def appendHowToRead(sb: StringBuilder): Unit = {
    sb.append("## How to read the tables\n\n")
    sb.append("- A time is the median wall clock time of the runs that found a solution, followed by how many of the runs did " +
      "(for example `1.90 s (5/5)`).\n")
    sb.append("- `no solution` means no run found a solution within the time limit. " +
      "A cell stops early after two runs in a row time out.\n")
    sb.append("- `error: ...` means the solver crashed with that exception when it was run. " +
      "A cell stops early after two runs in a row fail.\n")
    sb.append(s"- `$NOT_AVAILABLE` means that version of the library has no such algorithm, or the case was not run.\n")
    sb.append("- Tantrix variants use the first N tiles in numeric order. Each repetition seeds the shared random " +
      "generator, but the Tantrix simulated annealing and global hill climbing solvers create their own unseeded " +
      "generator, so their timings vary from run to run.\n\n")
  }

  private def puzzleNames(runs: List[RunRecord]): List[String] =
    runs.flatMap(_.results).map(_.puzzle).distinct

  private def appendPuzzle(sb: StringBuilder, puzzle: String, runs: List[RunRecord]): Unit = {
    val rows = rowKeys(puzzle, runs)
    val lookups = runs.map(r => r.results.filter(_.puzzle == puzzle).map(c => ((c.variant, c.algorithm), c)).toMap)
    val compare = runs.size > 1

    sb.append(s"## $puzzle\n\n")
    val titles = runs.map(columnTitle)
    val header = List("Variant", "Algorithm") ++ titles ++
      (if (compare) List(s"${runs.last.libVersion} vs ${runs.head.libVersion}") else Nil)
    sb.append(header.mkString("| ", " | ", " |\n"))
    sb.append(header.map(_ => "---").mkString("| ", " | ", " |\n"))

    rows.foreach { key =>
      val cells = runs.zip(lookups).map { case (run, byKey) =>
        byKey.get(key).map(c => cellText(c, run.timeoutSeconds)).getOrElse(NOT_AVAILABLE)
      }
      val change =
        if (compare) List(changeText(lookups.head.get(key), lookups.last.get(key)))
        else Nil
      sb.append((List(key._1, s"`${key._2}`") ++ cells ++ change).mkString("| ", " | ", " |\n"))
    }
    sb.append("\n")
  }

  /** All (variant, algorithm) pairs for the puzzle, grouped by variant, each in first-seen order. */
  private def rowKeys(puzzle: String, runs: List[RunRecord]): List[(String, String)] = {
    val pairs = runs.flatMap(_.results).filter(_.puzzle == puzzle).map(c => (c.variant, c.algorithm)).distinct
    pairs.map(_._1).distinct.flatMap(variant => pairs.filter(_._1 == variant))
  }

  def columnTitle(run: RunRecord): String = s"${run.libName} ${run.libVersion}"

  def cellText(c: CellResult, timeoutSeconds: Int): String =
    if (c.solved > 0) {
      val time = formatMillis(c.medianMillis.getOrElse(0L))
      if (c.attempts > 1) s"$time (${c.solved}/${c.attempts})" else time
    } else if (c.errored > 0) c.lastError.map(e => s"error: ${shorten(e)}").getOrElse("error")
    else if (c.timedOut > 0) s"no solution (timed out after ${timeoutSeconds}s)"
    else "no solution"

  /** Keeps an error description on one line and short enough for a table cell, without characters that break the table. */
  private def shorten(message: String): String = {
    val oneLine = message.replace('|', '/').replace('\n', ' ').replace('\r', ' ').trim
    if (oneLine.length <= MAX_ERROR_LENGTH) oneLine else oneLine.take(MAX_ERROR_LENGTH - 3) + "..."
  }

  private val MAX_ERROR_LENGTH = 90

  def formatMillis(ms: Long): String =
    if (ms < 1000L) s"$ms ms"
    else if (ms < 60000L) String.format(Locale.ROOT, "%.2f s", java.lang.Double.valueOf(ms / 1000.0))
    else {
      val minutes = ms / 60000L
      val seconds = (ms % 60000L) / 1000L
      val padded = if (seconds < 10L) s"0$seconds" else seconds.toString
      s"${minutes}m ${padded}s"
    }

  /** Compares the first (baseline) and last (newest) version for one row. */
  def changeText(baseline: Option[CellResult], newest: Option[CellResult]): String =
    (baseline, newest) match {
      case (Some(before), Some(after)) =>
        (before.medianMillis, after.medianMillis) match {
          case (Some(b), Some(a)) =>
            val ratio = (b max 1L).toDouble / (a max 1L).toDouble
            if (ratio >= 1.1) String.format(Locale.ROOT, "%.1fx faster", java.lang.Double.valueOf(ratio))
            else if (ratio <= 1.0 / 1.1) String.format(Locale.ROOT, "%.1fx slower", java.lang.Double.valueOf(1.0 / ratio))
            else "about the same"
          case (None, Some(_)) => "now solved"
          case (Some(_), None) => "no longer solved"
          case (None, None) => "-"
        }
      case _ => "-"
    }
}
